"""PM -> Trader -> Broker order schema for the simulated index fund.

Four linked tables, one row per object:

  pm_orders       What the portfolio manager wants: security, side, shares and the
                  benchmark the fund is measured against (CLOSE for an index
                  rebalance). Generated by the fund simulator; one per blotter row.
  trader_orders   How the desk works a PM order: execution strategy, time window,
                  participation cap. A PM order may be split across several
                  trader orders (e.g. 70% MOC + 30% VWAP).
  broker_orders   Child orders routed to a venue (MIC): order type, time-in-force,
                  limit, the time bucket it is live in.
  fills           Executions against child orders.

Quantities are unsigned shares; ``side`` carries the direction. Timestamps are
tz-naive America/New_York wall clock. Every table is a plain DataFrame, checked
by ``validate`` (columns, types, enums) and ``validate_links`` (foreign keys,
side consistency and quantity conservation down the chain).
"""
from __future__ import annotations

import hashlib

import numpy as np
import pandas as pd

SIDES = {"BUY", "SELL"}
REASONS = {"INITIAL", "REBALANCE", "INFLOW", "OUTFLOW"}
BENCHMARKS = {"CLOSE", "ARRIVAL", "VWAP"}
STRATEGIES = {"CLOSE_AUCTION", "VWAP", "ARRIVAL_IS"}
ORDER_TYPES = {"MOC", "LOC", "LIMIT", "MARKET", "MIDPOINT_PEG"}
TIFS = {"AT_CLOSE", "DAY", "IOC", "GTT"}            # GTT = good till bucket end
LIQUIDITY = {"AUCTION", "ADD", "REMOVE", "MIDPOINT", "DARK"}

# column -> (kind, required). kinds: str, int, float, ts, date, bool, or a set of allowed values
PM_ORDER = {
    "pm_order_id": ("str", True), "portfolio_id": ("str", True),
    "decision_date": ("date", True), "decision_ts": ("ts", True),
    "trade_date": ("date", True), "permno": ("int", True), "ticker": ("str", False),
    "side": (SIDES, True), "quantity": ("int", True), "decision_price": ("float", True),
    "reason": (REASONS, True), "benchmark": (BENCHMARKS, True),
    "urgency": ({"LOW", "MEDIUM", "HIGH"}, True), "notional_usd": ("float", True),
}
TRADER_ORDER = {
    "trader_order_id": ("str", True), "pm_order_id": ("str", True),
    "strategy": (STRATEGIES, True), "side": (SIDES, True), "quantity": ("int", True),
    "trade_date": ("date", True), "start_ts": ("ts", True), "end_ts": ("ts", True),
    "max_participation": ("float", True), "limit_price": ("float", False),
    "primary_mic": ("str", True),
}
BROKER_ORDER = {
    "child_order_id": ("str", True), "trader_order_id": ("str", True),
    "mic": ("str", True), "order_type": (ORDER_TYPES, True), "tif": (TIFS, True),
    "side": (SIDES, True), "quantity": ("int", True), "limit_price": ("float", False),
    "submit_ts": ("ts", True), "bucket_start": ("ts", True), "bucket_end": ("ts", True),
}
FILL = {
    "fill_id": ("str", True), "child_order_id": ("str", True), "mic": ("str", True),
    "fill_ts": ("ts", True), "side": (SIDES, True), "quantity": ("int", True),
    "price": ("float", True), "liquidity": (LIQUIDITY, True), "fee_usd": ("float", True),
    "impact_bps": ("float", False),
}
SCHEMAS = {"pm_orders": PM_ORDER, "trader_orders": TRADER_ORDER,
           "broker_orders": BROKER_ORDER, "fills": FILL}
KEYS = {"pm_orders": "pm_order_id", "trader_orders": "trader_order_id",
        "broker_orders": "child_order_id", "fills": "fill_id"}


def make_id(*parts, n=20):
    return hashlib.sha1("|".join(map(str, parts)).encode()).hexdigest()[:n]


def empty(table):
    return pd.DataFrame({c: pd.Series(dtype="object") for c in SCHEMAS[table]})


def validate(df, table):
    """Raise ValueError listing every schema violation in ``df``."""
    spec, problems = SCHEMAS[table], []
    missing = [c for c, (_, req) in spec.items() if req and c not in df]
    if missing:
        raise ValueError(f"{table}: missing columns {missing}")
    key = KEYS[table]
    if df[key].isna().any() or df[key].duplicated().any():
        problems.append(f"{key} null/duplicated")
    for col, (kind, req) in spec.items():
        if col not in df:
            continue
        s = df[col]
        if req and s.isna().any():
            problems.append(f"{col} has nulls")
        v = s.dropna()
        if isinstance(kind, set):
            bad = set(v) - kind
            if bad:
                problems.append(f"{col} invalid values {sorted(bad)[:5]}")
        elif kind in ("int", "float"):
            num = pd.to_numeric(v, errors="coerce")
            if num.isna().any() or not np.isfinite(num).all():
                problems.append(f"{col} not numeric/finite")
            elif kind == "int" and not np.allclose(num, np.round(num)):
                problems.append(f"{col} not whole")
        elif kind in ("ts", "date"):
            if pd.to_datetime(v, errors="coerce").isna().any():
                problems.append(f"{col} not a timestamp")
    if "quantity" in df and (pd.to_numeric(df.quantity, errors="coerce") <= 0).any():
        problems.append("quantity must be positive")
    for col in ("decision_price", "price", "limit_price"):
        if col in df and (pd.to_numeric(df[col], errors="coerce").dropna() <= 0).any():
            problems.append(f"{col} must be positive")
    if table == "trader_orders":
        if (pd.to_datetime(df.end_ts) < pd.to_datetime(df.start_ts)).any():
            problems.append("end_ts before start_ts")
        if not df.max_participation.between(0, 1, inclusive="right").all():
            problems.append("max_participation outside (0, 1]")
    if table == "broker_orders":
        if (pd.to_datetime(df.bucket_end) < pd.to_datetime(df.bucket_start)).any():
            problems.append("bucket_end before bucket_start")
        moc = df.order_type.isin(["MOC", "LOC"])
        if (moc & df.tif.ne("AT_CLOSE")).any():
            problems.append("MOC/LOC orders must be AT_CLOSE")
    if problems:
        raise ValueError(f"{table}: " + "; ".join(problems))
    return True


def validate_links(pm, trader, broker, fills=None):
    """Foreign keys, side consistency and quantity conservation.

    sum(trader.quantity) <= pm.quantity; sum(child.quantity) <= trader.quantity;
    sum(fill.quantity) <= child.quantity. Child buckets lie inside the trader window.
    """
    for df, name in ((pm, "pm_orders"), (trader, "trader_orders"), (broker, "broker_orders")):
        validate(df, name)
    problems = []

    def check(child, parent, fk, label):
        m = child.merge(parent[[fk, "side", "quantity"]], on=fk, how="left",
                        suffixes=("", "_parent"), indicator=True)
        if (m._merge != "both").any():
            problems.append(f"{label}: {int((m._merge != 'both').sum())} orphan rows")
        if (m.side != m.side_parent).dropna().any():
            problems.append(f"{label}: side differs from parent")
        tot = child.groupby(fk).quantity.sum()
        cap = parent.set_index(fk).quantity.reindex(tot.index)
        if (tot > cap + 1e-9).any():
            problems.append(f"{label}: {int((tot > cap).sum())} parents over-allocated")
    check(trader, pm, "pm_order_id", "trader->pm")
    check(broker, trader, "trader_order_id", "broker->trader")
    w = broker.merge(trader[["trader_order_id", "start_ts", "end_ts"]], on="trader_order_id")
    if ((pd.to_datetime(w.bucket_start) < pd.to_datetime(w.start_ts))
            | (pd.to_datetime(w.bucket_end) > pd.to_datetime(w.end_ts))).any():
        problems.append("broker bucket outside trader window")
    if fills is not None and len(fills):
        validate(fills, "fills")
        check(fills, broker, "child_order_id", "fill->broker")
    if problems:
        raise ValueError("; ".join(problems))
    return True


def pm_orders_from_blotter(blotter, *, portfolio_id="BMLL_SP500_10B", trade_date_col=None,
                           price_col=None, quantity_col=None, ticker_map=None,
                           decision_time="16:00"):
    """Fund simulator / handoff blotter -> pm_orders.

    Uses the split-adjusted execution basis when present (handoff file), so the
    quantity and decision price are in the share basis of the trade date.
    INITIAL/REBALANCE orders benchmark to CLOSE (the index trades the close);
    flow orders benchmark to ARRIVAL.
    """
    b = blotter.copy()
    q_col = quantity_col or ("signed_quantity_execution_basis" if "signed_quantity_execution_basis" in b
                             else "signed_quantity")
    p_col = price_col or ("decision_price_execution_basis" if "decision_price_execution_basis" in b
                          else "decision_price")
    t_col = trade_date_col or next(c for c in ("expected_execution_date", "execution_date")
                                   if c in b)
    qty = pd.to_numeric(b[q_col], errors="raise")
    reason = b["reason"] if "reason" in b else pd.Series("REBALANCE", index=b.index)
    out = pd.DataFrame({
        "pm_order_id": b["order_id"].astype(str) if "order_id" in b else [
            make_id(d, p, r) for d, p, r in zip(b.decision_date, b.permno, reason)],
        "portfolio_id": portfolio_id,
        "decision_date": pd.to_datetime(b.decision_date).dt.normalize(),
        "trade_date": pd.to_datetime(b[t_col]).dt.normalize(),
        "permno": b.permno.astype(int),
        "side": np.where(qty > 0, "BUY", "SELL"),
        "quantity": qty.abs().round().astype(int),
        "decision_price": pd.to_numeric(b[p_col], errors="raise").astype(float),
        "reason": reason.astype(str).values,
    })
    out["decision_ts"] = out.decision_date + pd.Timedelta(decision_time + ":00")
    out["benchmark"] = np.where(out.reason.isin(["INITIAL", "REBALANCE"]), "CLOSE", "ARRIVAL")
    out["urgency"] = np.where(out.reason.eq("OUTFLOW"), "HIGH", "MEDIUM")
    out["notional_usd"] = out.quantity * out.decision_price
    if ticker_map is not None:
        out["ticker"] = out.permno.map(ticker_map)
    out = out[out.quantity > 0].reset_index(drop=True)
    validate(out, "pm_orders")
    return out
